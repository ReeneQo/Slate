/**
 * Единая точка обработки 401 — точка расширения, не заглушка-редирект.
 *
 * Роутера и auth-стора ещё нет (появятся в SLT-25), поэтому здесь клиент НЕ редиректит и НЕ
 * трогает состояние — он лишь уведомляет одного зарегистрированного обработчика, что сервер
 * ответил 401. SLT-25 подключит сюда сброс auth-состояния (и, при желании, навигацию на
 * /login). Пока обработчик не зарегистрирован — `notifyUnauthorized` просто ничего не делает.
 *
 * Почему один обработчик, а не список подписчиков: реакция на «сессия истекла» ровно одна —
 * сбросить auth. Массив слушателей создал бы иллюзию, что их может быть много, и вопрос
 * порядка/идемпотентности на пустом месте. KISS: один слот, повторная регистрация замещает.
 */

type UnauthorizedHandler = () => void;

let handler: UnauthorizedHandler | null = null;

/**
 * Регистрирует обработчик 401. Возвращает функцию отписки (снять обработчик — например, в
 * cleanup эффекта), чтобы не оставлять висящую ссылку на размонтированный стор.
 */
export function registerUnauthorizedHandler(next: UnauthorizedHandler): () => void {
  handler = next;
  return () => {
    // Снимаем только если с тех пор никто не перерегистрировался — иначе затрём чужой обработчик.
    if (handler === next) {
      handler = null;
    }
  };
}

/** Вызывается транспортом при 401. Внутренняя точка — фичи её не дёргают напрямую. */
export function notifyUnauthorized(): void {
  handler?.();
}
