import { QueryClient } from '@tanstack/react-query';

import { isApiError } from '@/shared/api';

/**
 * Дефолты react-query заданы ПОД НАШ контракт, а не библиотечные — стоковые настройки собраны
 * под данные, которые часто меняются и дёшевы для перезапроса, а у нас доски меняются редко и
 * ходят через сессионный API.
 *
 * `retry` — предикат, а не число. Клиентские ошибки (4xx: 401 «сессия истекла», 403 «чужое»,
 * 404 «удалено», 422 «невалидно») ДЕТЕРМИНИРОВАНЫ: повтор того же запроса даст тот же ответ,
 * только задержит показ ошибки пользователю и лишний раз ударит по бэку. Их не ретраим вовсе.
 * Сетевые сбои и 5xx — преходящие: до трёх попыток суммарно. Статус берём из типизированной
 * `ApiError` (SLT-24); не-`ApiError` (например, брошенное из парсинга) считаем преходящим.
 *
 * `staleTime` 5 минут: пока данные «свежие», react-query не перезапрашивает их на каждом
 * маунте/рефокусе. Для редко меняющегося списка досок это убирает шквал лишних `GET /boards`.
 *
 * `refetchOnWindowFocus: false`: приложение не realtime (сокеты — этап 3), автodrag данных при
 * каждом возврате на вкладку — это трафик без пользы. Обновление списка обеспечивают точечные
 * инвалидации после мутаций, а не фоновый рефетч.
 *
 * `mutations.retry` не трогаем (дефолт 0): POST/DELETE не идемпотентны для слепого повтора —
 * повторное создание завело бы дубль доски. Ретраить мутацию можно лишь осознанно и точечно.
 */
export function createQueryClient(): QueryClient {
  return new QueryClient({
    defaultOptions: {
      queries: {
        staleTime: 5 * 60 * 1000,
        refetchOnWindowFocus: false,
        retry: (failureCount, error) => {
          if (isApiError(error) && error.status >= 400 && error.status < 500) {
            return false;
          }
          return failureCount < 2;
        },
      },
    },
  });
}
