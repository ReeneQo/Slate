import type { SaveErrorKind } from './useCanvasSync';

/**
 * Текст баннера по причине (SLT-40 Р5, дополнено SLT-43) — отдельный файл, а не внутри
 * `SyncErrorBanner.tsx`: файл компонента обязан экспортировать ТОЛЬКО компоненты
 * (react-refresh/only-export-components), а маппинг «причина → текст» тестируется отдельно
 * (в проекте нет компонентных/RTL-тестов, см. остальные lib-функции виджета).
 *
 * ТРИ ТЕКСТА, НЕ ОДИН: `network` — сеть/сервер мертвы, действие юзера — просто ждать (autosave
 * повторит попытку на следующем изменении). `conflict` — version_conflict: сервер уже принял чужую
 * правку раньше, ваша отклонена и стор уже показывает актуальное серверное состояние
 * (last-write-wins, useCanvasSync/sendMutation) — действие юзера другое: не «подождать сеть», а
 * «посмотреть, что стало, и решить, повторять ли правку». `forbidden` — своя мутация отклонена по
 * роли (понижен editor→viewer или отозван, пока оставался на доске, SLT-41/43) — действие юзера
 * снова другое: повтор бессмысленен, надо узнать/дождаться, пока доступ вернут. Прочие причины
 * отказа (access_denied/not_found/invalid_payload/create-conflict) делят текст с `network` — они
 * баги/граничные случаи, не штатный конфликт редактирования, отдельный текст под них не оправдан
 * (Р5, «минимально»).
 */
export function syncErrorMessage(kind: SaveErrorKind): string {
  switch (kind) {
    case 'conflict':
      return 'Элемент изменён другим участником — ваша правка не применена';
    case 'forbidden':
      return 'Доступ к доске изменён — у вас больше нет прав на редактирование';
    case 'network':
      return 'Не удалось сохранить изменения — проблема с сетью';
  }
}
