import type { BoardAccessRole } from '@slate/shared-types';

/**
 * Единая производная «может ли текущий юзер мутировать холст» (SLT-43, решение 1) —
 * `owner`/`editor` да, `viewer` и «роль ещё не известна» (`undefined`, `GET /boards` в полёте
 * или доска не найдена в списке) нет. Безопасный дефолт: пока роль не подтверждена, холст
 * read-only, а не «разрешить и откатить по 403» — тулбар и обработчики появляются, как только
 * `useBoardRole` резолвится, а не мигают доступными на старте.
 *
 * ЧИСТАЯ функция, не хук: единственная точка правды для гейта, от которой зависят и editor-стор
 * (`setCanEdit`), и её собственный юнит-тест — без монтирования Konva/React (в проекте нет
 * компонентных тестов, см. другие lib-функции виджета).
 */
export function deriveCanEdit(role: BoardAccessRole | undefined): boolean {
  return role === 'owner' || role === 'editor';
}
