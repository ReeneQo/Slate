import { Injectable } from '@nestjs/common';
import * as argon2 from 'argon2';

/**
 * Параметры argon2id — заданы ЯВНО и в одном месте.
 *
 * Значения — минимум из OWASP Password Storage Cheat Sheet для argon2id:
 * m=19456 KiB (19 MiB), t=2, p=1. Голый `argon2.hash(plain)` тоже даёт argon2id,
 * но его дефолты — деталь реализации библиотеки: молча поедут при обновлении пакета,
 * и стойкость хранимых хешей изменится без единой строчки в нашем диффе.
 *
 * memoryCost — главный параметр против GPU/ASIC-перебора: атака упирается в память,
 * а не в вычисления. timeCost/parallelism балансируют это с латентностью логина.
 */
const ARGON2_OPTIONS = {
  type: argon2.argon2id,
  memoryCost: 19456,
  timeCost: 2,
  parallelism: 1,
} as const satisfies argon2.Options;

/**
 * Хеширование паролей. Выделено в отдельный сервис, а не размазано по UserService:
 *
 * - параметры живут в ОДНОЙ точке (иначе регистрация и смена пароля разъезжаются
 *   по стойкости — классика: один вызов с опциями, второй без);
 * - блок 5 (смена/сброс пароля) переиспользует его без дублирования;
 * - смена алгоритма или подкрутка параметров — правка одного файла;
 * - тестируется изолированно, а в тестах домена подменяется быстрым моком
 *   (argon2 по построению медленный — это его работа, но не работа юнит-тестов).
 *
 * Живёт в `shared/`, а не в `modules/user` или `modules/auth`: хеширование нужно
 * обоим, и класть его в один из них — значит заставить второй импортировать чужой
 * доменный модуль ради утилиты. В `infrastructure/` тоже не место: там вещи с
 * подключением и жизненным циклом (Prisma, Redis), здесь же чистая CPU-функция.
 */
@Injectable()
export class HashService {
  hash(plain: string): Promise<string> {
    return argon2.hash(plain, ARGON2_OPTIONS);
  }

  /**
   * Параметры (память/итерации/соль) argon2 хранит внутри самой строки хеша, поэтому
   * verify их не принимает: старые хеши проверяются корректно даже после того, как мы
   * поднимем ARGON2_OPTIONS. Порядок аргументов — (хеш, пароль), как в argon2.
   *
   * Ошибку намеренно НЕ глушим в `false`: битая строка хеша — это порча данных, а не
   * неверный пароль. Проглотив её, мы бы превратили инцидент целостности БД в обычный
   * «неверный пароль» и никогда о нём не узнали.
   */
  verify(hash: string, plain: string): Promise<boolean> {
    return argon2.verify(hash, plain);
  }
}
