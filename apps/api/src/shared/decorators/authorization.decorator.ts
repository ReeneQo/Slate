import { applyDecorators, UseGuards } from '@nestjs/common';

import { AuthGuard } from '../guards/auth.guard';

/**
 * Маркер «этот роут требует входа».
 *
 * Сейчас за ним ровно один guard, и `@UseGuards(AuthGuard)` дал бы тот же результат.
 * Смысл обёртки не в экономии символов, а в том, что точка подключения защиты — одна:
 * когда появится второй кросс-роутовый guard (в этапе 3 — проверка живой сессии для
 * WebSocket-хендшейка), его добавят здесь, и все защищённые роуты получат его разом.
 * С россыпью `@UseGuards` по контроллерам такое изменение — это правка каждого файла,
 * где кто-нибудь обязательно окажется пропущен.
 *
 * Ролей тут нет намеренно. В старом проекте композит принимал `@Authorization(UserRole.ADMIN)`
 * и тянул за собой RolesGuard; в Slate глобальных ролей не существует — права определяются
 * членством в конкретной доске (BoardMember.role) и проверяются в board-модуле, где известно,
 * о какой доске речь. Параметр роли здесь было бы просто некуда девать.
 */
export function Authorization(): MethodDecorator & ClassDecorator {
  return applyDecorators(UseGuards(AuthGuard));
}
