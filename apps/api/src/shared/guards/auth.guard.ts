import {
  type CanActivate,
  type ExecutionContext,
  Injectable,
  UnauthorizedException,
} from '@nestjs/common';
import type { Request } from 'express';

/**
 * «Есть ли активная сессия» — и ничего больше.
 *
 * Ключевое отличие от одноимённого guard'а старого проекта: тот на КАЖДЫЙ защищённый
 * запрос грузил пользователя из БД вместе со связанным account, да ещё и подписывал
 * S3-ссылку на аватар. Итог — лишний round-trip к базе на каждом чихе (включая эндпоинты,
 * которым пользователь не нужен вовсе) и мутация req.user, о которой не знал никто, кроме
 * автора. Здесь guard отвечает ровно на свой вопрос — пускать или нет, — а полного
 * пользователя грузит тот, кому он действительно нужен (AuthService.getMe).
 *
 * Плата за отказ от запроса в БД: сессия остаётся валидной до истечения TTL, даже если
 * пользователя удалили. Это осознанный размен — удаление аккаунта редкое, и закрывается
 * оно инвалидацией сессий в момент удаления, а не round-trip'ом на каждом запросе.
 * Эндпоинты, которым нужен актуальный пользователь, всё равно идут в БД и получают там
 * null (см. getMe → 401).
 *
 * Никакой проверки ролей: в Slate роль — это членство в конкретной доске (BoardMember.role),
 * а не глобальный атрибут пользователя. Проверять её на входе в запрос попросту негде,
 * поэтому она и живёт в board-модуле (SLT-17), а не здесь.
 */
@Injectable()
export class AuthGuard implements CanActivate {
  canActivate(context: ExecutionContext): boolean {
    const request = context.switchToHttp().getRequest<Request>();

    // Бросаем исключение, а НЕ возвращаем false: на false Nest отвечает 403 Forbidden
    // («ты опознан, но тебе нельзя»), тогда как отсутствие сессии — это 401 Unauthorized
    // («представься»). Фронт различает их по-разному: на 401 он ведёт на логин, а на 403
    // показал бы «нет доступа» гостю, которому достаточно было войти.
    if (request.session?.userId === undefined) {
      throw new UnauthorizedException('Требуется авторизация');
    }

    return true;
  }
}
