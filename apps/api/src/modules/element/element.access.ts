import type { Prisma } from '@slate/database';

import { accessibleBoardScope } from '../board/board.access';

/**
 * Область видимости КОНКРЕТНОГО элемента.
 *
 * Второй проверки доступа здесь нет — есть переиспользование первой. Доступ к элементу
 * определяется доступом к его доске, поэтому scope доски (SLT-19) вклеивается в условие
 * запроса элемента фильтром по связи: `board: { OR: [{ ownerId }] }`. Когда на этапе 3
 * появится шеринг, ветка допишется в `accessibleBoardScope` — и элементы станут доступны
 * участникам сами собой, без единой правки здесь. Своя копия правила («прочитать элемент,
 * сходить за его доской, сравнить ownerId») была бы второй авторизацией, которую нужно
 * править синхронно с первой, — и однажды не поправят.
 *
 * Форма — фрагмент `where`, а не булев ответ, по тем же двум причинам, что у доски
 * (см. board.access.ts): чужая строка не попадает в память процесса, а проверка и мутация
 * выполняются одним запросом, без окна между ними.
 *
 * Тип подходит и `ElementWhereInput` (findFirst), и `ElementWhereUniqueInput` (update через
 * extendedWhereUnique): `id` — первичный ключ, `board` — фильтр по связи, доступный в обоих.
 * Один scope на все операции над элементом — не бывает операции, «для которой пришлось
 * написать проверку иначе».
 *
 * Чего здесь НЕТ намеренно — `deletedAt: null`. Мягкое удаление это не про доступ, а про
 * состояние строки, и смешивать их нельзя: воскрешение через PUT обязано ВИДЕТЬ удалённый
 * элемент, оставаясь под тем же ограничением доступа.
 */
export function accessibleElementScope(
  elementId: string,
  userId: string,
): { id: string; board: Prisma.BoardWhereInput } {
  return { id: elementId, board: accessibleBoardScope(userId) };
}
