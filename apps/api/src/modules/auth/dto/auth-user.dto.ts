import type { SafeUser } from '../../user/entities/user.entity';

/**
 * Ответ на register/login: «кто только что вошёл».
 *
 * Минимальный набор — ровно то, чем фронт заполняет шапку сразу после входа. Тип отдельный
 * от `UserResponseDto` (ответ GET /auth/me) — потому что эндпоинты отвечают на разные
 * вопросы, а не потому что «так аккуратнее»:
 *
 * - `hasPassword` здесь бессмыслен: войти по паролю, не имея пароля, невозможно, так что
 *   поле было бы константным `true` — шум в контракте, который фронт однажды примет за
 *   значащий и начнёт на нём что-то строить;
 * - `createdAt` при входе не нужен: дата регистрации — это профиль, а не сессия.
 *
 * Если однажды окажется, что оба ответа обязаны совпадать, слить их — правка одного
 * маппера. Обратная операция (расщепить общий DTO, когда контракты разъехались) стоит
 * заметно дороже, и делать её приходится уже под давлением фронта.
 */
export interface AuthUserDto {
  id: string;
  email: string;
  displayName: string;
}

/**
 * Принимает `SafeUser`, но поля перечислены ПОИМЁННО, а не через spread. Это защита,
 * а не стиль: `UserWithHash` структурно совместим с `SafeUser`, поэтому пользователь
 * ВМЕСТЕ С ХЕШЕМ пройдёт в этот параметр без единой ошибки типов — что и происходит в
 * `AuthService.login`, где на руках именно `UserWithHash`. Со spread'ом `passwordHash`
 * уехал бы прямо в HTTP-ответ (ровно тот баг, что был в старом проекте). Явный перечень
 * делает утечку невозможной независимо от того, что передали.
 */
export function toAuthUser(user: SafeUser): AuthUserDto {
  return {
    id: user.id,
    email: user.email,
    displayName: user.displayName,
  };
}
