import { IsEmail, IsNotEmpty, IsString, MaxLength, MinLength } from 'class-validator';

/**
 * Границы длины пароля.
 *
 * MIN — нижняя планка NIST SP 800-63B. Правил сложности (заглавная/цифра/спецсимвол)
 * НЕТ намеренно: тот же стандарт от них отговаривает, потому что они предсказуемо
 * порождают `Password1!` вместо действительно длинной парольной фразы.
 *
 * MAX — это НЕ про UX, а защита сервера. Без верхней границы клиент присылает пароль на
 * мегабайт, и argon2 честно жжёт на нём CPU и 19 МиБ памяти — несколько параллельных
 * запросов кладут инстанс, причём совершенно легально, ещё до всякой аутентификации.
 * 72 — исторический предел bcrypt; argon2 им не ограничен, но число достаточное и
 * узнаваемое, а гнаться тут не за чем.
 */
const PASSWORD_MIN_LENGTH = 8;
const PASSWORD_MAX_LENGTH = 72;

/** Верхняя граница имени — чтобы в БД и в чужие интерфейсы не уезжал текст произвольного размера. */
const DISPLAY_NAME_MAX_LENGTH = 100;

/**
 * Вход регистрации.
 *
 * `passwordRepeat` из старого проекта не переносим. Совпадение двух полей — свойство
 * ФОРМЫ, а не запроса: сервер получает один пароль и не может сказать, что пользователь
 * имел в виду. Проверять это должен фронт (блок 4), там же, где оба поля и существуют.
 * На сервере поле давало бы лишь ложное ощущение проверки и лишний элемент контракта.
 *
 * Поле называется `displayName`, а не `name` (как в оригинале) — ровно как колонка в
 * схеме. Разные имена по краям одного пути данных означают маппинг «туда-обратно» и
 * вопрос «это точно то же самое поле?» при каждом чтении.
 */
export class RegisterDto {
  @IsEmail({}, { message: 'Некорректный email' })
  email!: string;

  @IsString()
  @IsNotEmpty({ message: 'Имя не может быть пустым' })
  @MaxLength(DISPLAY_NAME_MAX_LENGTH, {
    message: `Имя не длиннее ${DISPLAY_NAME_MAX_LENGTH} символов`,
  })
  displayName!: string;

  @IsString()
  @MinLength(PASSWORD_MIN_LENGTH, { message: `Пароль не короче ${PASSWORD_MIN_LENGTH} символов` })
  @MaxLength(PASSWORD_MAX_LENGTH, { message: `Пароль не длиннее ${PASSWORD_MAX_LENGTH} символов` })
  password!: string;
}
