import { Injectable } from '@nestjs/common';

import { RedisService } from '../../../infrastructure/redis/redis.service';

/**
 * Ключ счётчика поколения сессий одного пользователя.
 *
 * Формат домена — не инфраструктуры: `RedisService` намеренно «тупой» и знает только про
 * коннект, а какими ключами пользоваться — решает тот, кто владеет смыслом данных. Поэтому
 * формат живёт здесь, в auth-территории, а не в общем redis-модуле.
 */
function sessionGenerationKey(userId: string): string {
  return `user:${userId}:sessionGen`;
}

/**
 * «Поколение» сессий пользователя — счётчик, сдвиг которого разом обесценивает все сессии,
 * выпущенные до сдвига. Это и есть механизм «выйти на всех устройствах» без перечисления
 * самих сессий: до чужих записей `sess:<sid>` под случайными идентификаторами дотянуться
 * нельзя, а один общий счётчик — можно.
 *
 * Как это работает вместе:
 *   - при создании сессии (login/register) в неё кладётся СНИМОК текущего поколения;
 *   - guard на каждом защищённом запросе сверяет снимок из сессии с актуальным поколением;
 *   - расхождение → сессия недействительна (её выпустили до сдвига) → 401;
 *   - logout-everywhere просто инкрементит счётчик — и все прежние снимки разом устаревают.
 *
 * ОТСУТСТВИЕ КЛЮЧА = ПОКОЛЕНИЕ 0. Ключ не инициализируется при login специально: это лишняя
 * запись на каждый вход и гонка «инициализация против инкремента». Вместо этого отсутствие
 * трактуется как 0 в ОБЕИХ точках чтения (здесь и в guard), а `INCR` по несуществующему ключу
 * сам заводит его значением 1 — ровно то, что нужно: первый logout-all уводит поколение с
 * подразумеваемого 0 на явную 1. Никакой отдельной инициализации не требуется, и семантика
 * остаётся согласованной без единого лишнего обращения к Redis.
 *
 * БЕЗ TTL. Счётчик — крошечное целое на пользователя, который хоть раз делал logout-all, и
 * живёт он вечно осознанно. TTL короче времени жизни сессии был бы прямым багом: истеки ключ
 * раньше сессии — `getCurrent` вернул бы 0, снимок в живой сессии остался бы 1, и guard вышиб
 * бы ДЕЙСТВИТЕЛЬНУЮ сессию на ровном месте. Сброс же всего Redis (единственное, что обнуляет
 * поколения) и так уносит все сессии, поэтому обнуление счётчиков новой уязвимости не создаёт.
 */
@Injectable()
export class SessionGenerationService {
  constructor(private readonly redis: RedisService) {}

  /**
   * Актуальное поколение пользователя. Отсутствие ключа — это 0, а не ошибка: пользователь,
   * ни разу не делавший logout-all, просто не имеет записи, и его сессии сверяются с нулём.
   */
  async getCurrent(userId: string): Promise<number> {
    const raw = await this.redis.client.get(sessionGenerationKey(userId));

    // `INCR` пишет только целые строки, поэтому единственная реальная ветка «не число» —
    // это null отсутствующего ключа. Приводим её к 0 явно.
    return raw === null ? 0 : Number.parseInt(raw, 10);
  }

  /**
   * Сдвигает поколение вперёд и возвращает новое значение. `INCR` атомарен — два
   * параллельных logout-all не потеряют инкремент друг друга, — и заводит ключ значением 1,
   * если его ещё не было (см. «отсутствие = 0» выше).
   */
  bump(userId: string): Promise<number> {
    return this.redis.client.incr(sessionGenerationKey(userId));
  }
}
