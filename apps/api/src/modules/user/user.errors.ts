/**
 * Доменные ошибки модуля user.
 *
 * Это НЕ HttpException и не Prisma-ошибка — намеренно. Ошибка рождается на границе с ORM
 * (только репозиторий видит код P2002), а решение «какой это HTTP-статус» принимает тот,
 * кто обслуживает конкретный сценарий: при регистрации занятый email — это 409, при
 * импорте пользователей пачкой он же может означать «пропустить строку».
 *
 * Бросать отсюда ConflictException значило бы вшить HTTP в слой данных: модуль стал бы
 * непригоден для CLI-скрипта или воркера, где никакого запроса нет.
 */

/**
 * Email уже занят. Единственный надёжный источник этого факта — unique-constraint БД,
 * поэтому ошибка появляется ПОСЛЕ попытки вставки, а не вместо неё (см. UserRepository.create).
 */
export class EmailAlreadyTakenError extends Error {
  constructor(public readonly email: string) {
    super(`Email уже занят: ${email}`);
    this.name = 'EmailAlreadyTakenError';
  }
}
