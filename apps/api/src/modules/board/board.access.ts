import type { Prisma } from '@slate/database';

/**
 * ЕДИНСТВЕННОЕ определение «эта доска доступна этому пользователю».
 *
 * Возвращает не булево значение, а ОБЛАСТЬ ВИДИМОСТИ запроса — фрагмент `where`. Разница
 * принципиальная, и она в двух вещах:
 *
 * 1. Безопасность чтения. Вариант «прочитать доску, потом сравнить ownerId» означает, что
 *    чужая строка уже в памяти процесса: она попадёт в стек ошибки, в дамп, в лог отладки.
 *    Здесь БД просто не отдаёт то, к чему нет доступа, — данных, которых нельзя показывать,
 *    в приложении не существует.
 * 2. Атомарность записи. PATCH и DELETE применяют scope в том же запросе, что и мутацию.
 *    Отдельная проверка «можно ли» перед отдельным `update` оставляет окно между ними
 *    (TOCTOU): доска может исчезнуть ровно в этом промежутке.
 *
 * Почему `OR` с одним элементом, а не `{ ownerId: userId }`. Это заготовка расширения,
 * которое уже известно: на этапе 3 появится шеринг, и доступ станет «владелец ИЛИ участник».
 * В такой форме это ДОПИСЫВАНИЕ ветки в массив:
 *
 *   OR: [{ ownerId: userId }, { members: { some: { userId } } }]
 *
 * а не переписывание условия. Разница не в экономии символов: переписывать пришлось бы
 * условие, от которого зависит вся авторизация модуля, — то есть трогать работающую
 * проверку доступа вместо того, чтобы добавить к ней случай.
 *
 * Тип возврата — `{ OR: Prisma.BoardWhereInput[] }`, и это тоже намеренно: такая форма
 * подходит и `BoardWhereInput` (findFirst/findMany), и `BoardWhereUniqueInput` (update/delete
 * через extendedWhereUnique). Один и тот же scope применяется ко ВСЕМ операциям над
 * конкретной доской — не бывает операции, для которой «пришлось написать проверку иначе».
 *
 * Область — single-owner: BoardMember в схеме есть, но логика шеринга относится к этапу 3,
 * и заранее её здесь нет. Иначе получилась бы никем не вызванная и ничем не проверенная
 * ветка авторизации — худший вид мёртвого кода.
 */
export function accessibleBoardScope(userId: string): { OR: Prisma.BoardWhereInput[] } {
  return { OR: [{ ownerId: userId }] };
}
