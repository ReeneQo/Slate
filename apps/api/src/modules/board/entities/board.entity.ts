import type { Prisma } from '@slate/database';

/**
 * Набор полей доски, который вообще покидает репозиторий. ИСТОЧНИК ИСТИНЫ — этот select,
 * тип ниже выводится из него, поэтому разъехаться они не могут.
 *
 * `version` в списке НЕТ — и это не то же самое, что «не отдавать его в DTO». Без select
 * Prisma тянет строку целиком, и счётчик ревизий реально лежит в объекте: гуляет по памяти,
 * попадает в любой `JSON.stringify` — в лог, в ответ, в трассировку ошибки. `Omit<Board, 'version'>`
 * спрятал бы его только от компилятора; тип, расходящийся с рантаймом, — это не защита, а её
 * иллюзия (та же логика, что у SAFE_USER_SELECT и хеша пароля).
 *
 * До этапа 3 version клиенту не нужен: оптимистической блокировки ещё нет, а поле, которое
 * никто не читает, в контракте означает лишь обещание, которое придётся поддерживать. Когда
 * блокировка появится, его добавят сюда и в DTO — ОДНИМ осознанным изменением.
 *
 * `as const` обязателен: без него `id: true` выводится как `boolean`, и Prisma не сможет
 * вывести форму результата. `satisfies` проверяет, что все ключи существуют в модели, —
 * опечатка в имени поля не доживёт до рантайма.
 */
export const BOARD_SELECT = {
  id: true,
  title: true,
  createdAt: true,
  updatedAt: true,
} as const satisfies Prisma.BoardSelect;

/** Доска в том виде, в каком её видит сервис: без version, без связей. */
export type BoardEntity = Prisma.BoardGetPayload<{ select: typeof BOARD_SELECT }>;
