import type { BoardEntity } from '../entities/board.entity';

/**
 * Форма доски, уходящая на фронт. Отдельный тип, а не Prisma-модель: форма ответа — контракт
 * с клиентом, и она не обязана повторять форму таблицы. Отдавая наружу тип модели, мы бы
 * привязали публичный API к схеме БД — новая колонка автоматически утекала бы в ответ.
 *
 * `version` нет: до этапа 3 оптимистической блокировки не существует, и клиенту с ним нечего
 * делать (в выборке репозитория его тоже нет — см. BOARD_SELECT).
 *
 * `updatedAt` есть, в отличие от UserResponseDto. Это не «отдаём всё, что найдётся»: список
 * досок отсортирован по последнему изменению, и интерфейсу нужно показать «изменено N назад».
 * Поле работающее, поэтому и в контракте.
 */
export interface BoardDto {
  id: string;
  title: string;
  createdAt: Date;
  updatedAt: Date;
}

/**
 * Маппер сущность → DTO. Поля перечислены ПОИМЁННО, без `{ ...board }`.
 *
 * Это не занудство, а страховка на будущее: сегодня BoardEntity и BoardDto совпадают, но
 * стоит этапу 3 добавить `version: true` в BOARD_SELECT (для оптимистической блокировки
 * счётчик нужен серверу), и spread начнёт молча отдавать его наружу. Явный перечень делает
 * состав ответа решением, а не следствием того, что понадобилось в запросе.
 */
export function toBoardDto(board: BoardEntity): BoardDto {
  return {
    id: board.id,
    title: board.title,
    createdAt: board.createdAt,
    updatedAt: board.updatedAt,
  };
}
