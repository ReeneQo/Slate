/**
 * Лимиты троттлинга — КОНСТАНТЫ в коде, а не env. Это часть поведения приложения (сколько
 * запросов в секунду оно считает нормой), а не конфигурация окружения: значение не зависит от
 * того, где приложение запущено, и не должно меняться разработчиком в своём `.env`.
 *
 * Числа заданы один раз здесь и переиспользуются в ДВУХ местах, которые обязаны совпадать:
 * в глобальном объявлении троттлеров (throttler.module) и в точечных декораторах на роутах
 * (@Throttle на element-контроллере). Разъедься они — и потолок в объявлении разошёлся бы с
 * потолком на роуте молча.
 */
const MINUTE_MS = 60_000;

/**
 * Имена троттлеров. @Throttle/@SkipThrottle адресуют конкретный именованный лимит по строке —
 * держим её в одном месте, чтобы опечатка в декораторе не создала «третий» безымянный троттлер,
 * который никогда не сработает.
 */
export const THROTTLER_DEFAULT = 'default';
export const THROTTLER_AUTOSAVE = 'autosave';

/**
 * Baseline на ВСЕ роуты: 100 запросов / 60 сек на клиента. Щедро для живого пользователя
 * (клики, навигация, загрузка досок), но конечно — перебор login/register или флуд CRUD
 * упрётся в потолок. Вешается глобально через APP_GUARD.
 */
export const DEFAULT_LIMIT = { limit: 100, ttl: MINUTE_MS };

/**
 * Autosave-путь (мутации элементов, SLT-27): ~600 запросов / 60 сек ≈ 10 rps устойчиво.
 * Живое рисование — это поток действий, каждое из которых летит отдельным autosave-запросом;
 * упрись он в baseline (100), фронт показал бы баннер «не удалось сохранить» посреди обычной
 * работы. Лимит щедрый, но конечный: защита от бесконечного цикла на клиенте остаётся.
 */
export const AUTOSAVE_LIMIT = { limit: 600, ttl: MINUTE_MS };
