import { loadSwcConfig } from './jest.swc.mjs';

/**
 * Первый прогон тянет образы postgres:16 и redis:7 из реестра — это десятки секунд, и
 * дефолтные 5 000 мс Jest срезали бы его на `beforeAll` с бесполезным «Exceeded timeout».
 * Дальше образы лежат в локальном кеше Docker, и старт пары контейнеров укладывается в
 * пару секунд, так что запас никого не задерживает — он тратится только когда реально нужен.
 */
const CONTAINER_STARTUP_TIMEOUT_MS = 60_000;

/**
 * E2E-раннер: настоящий HTTP поверх настоящих Postgres и Redis в эфемерных контейнерах.
 *
 * Отдельный конфиг, а не флаг к основному, потому что у раннеров разная цена и разный повод
 * запуска. Юниты — это то, что гоняют на каждое сохранение; e2e требуют живого Docker-демона
 * и минуты на холодный старт. Слив их в один прогон, мы бы получили либо медленный
 * `pnpm test`, либо (что хуже) e2e, которые молча не запускаются там, где Docker недоступен.
 *
 * SWC-трансформация — та же функция, что у юнитов (jest.swc.mjs), а не копия: e2e поднимает
 * настоящий DI-контейнер Nest, и расхождение в `decoratorMetadata` сломало бы его первым.
 *
 * ВАЖНО про запуск. Скрипт test:e2e зовёт Jest через `node --experimental-vm-modules`, и это
 * не украшательство: Prisma 7 подгружает свой WASM-компилятор запросов динамическим import(),
 * а CJS-песочница Jest без этого флага отвечает «A dynamic import callback was invoked without
 * --experimental-vm-modules». Падает при этом не тест, а `app.init()` — выглядит как сломанное
 * приложение, хотя сломан только раннер. Юнитов это не касается: они не создают PrismaClient.
 *
 * @type {import('jest').Config}
 */
export default {
  rootDir: '.',
  roots: ['<rootDir>/test'],
  testEnvironment: 'node',
  testMatch: ['**/*.e2e-spec.ts'],
  moduleFileExtensions: ['ts', 'js', 'json'],

  transform: {
    '^.+\\.ts$': ['@swc/jest', loadSwcConfig()],
  },

  testTimeout: CONTAINER_STARTUP_TIMEOUT_MS,

  // Файлы гоняются В ОДИН ПОТОК. Сейчас файл всего один, так что на скорость это не влияет,
  // а вот на корректность повлияет сразу, как появится второй (board — блок 3): параллельные
  // воркеры Jest — это отдельные процессы, каждый поднял бы свою пару контейнеров и свой
  // инстанс приложения. На слабой машине это кратный расход памяти, а Docker-демон в WSL
  // под таким наплывом начинает отдавать таймауты вместо контейнеров.
  maxWorkers: 1,

  // Покрытие с e2e не собираем: оно считалось бы по тому же src, что и у юнитов, и два
  // отчёта пришлось бы мержить. Цифра покрытия — забота юнит-раннера, дело e2e — контракт.
  collectCoverage: false,
};
