import { loadSwcConfig } from './jest.swc.mjs';

/**
 * Первый прогон тянет образы postgres:16 и redis:7 из реестра — это десятки секунд. Само
 * подтягивание образов происходит в globalSetup (не ограничено testTimeout — у global-хуков
 * Jest своего таймаута нет), но testTimeout остаётся тем же запасом: он всё ещё нужен внутри
 * файлов — например, realtime-адаптер ждёт сетевой broadcast между двумя живыми инстансами,
 * и 5 000 мс по умолчанию для такого сценария тесны и без контейнеров.
 */
const CONTAINER_STARTUP_TIMEOUT_MS = 60_000;

/**
 * E2E-раннер: настоящий HTTP поверх настоящих Postgres и Redis в эфемерных контейнерах.
 *
 * Отдельный конфиг, а не флаг к основному, потому что у раннеров разная цена и разный повод
 * запуска. Юниты — это то, что гоняют на каждое сохранение; e2e требуют живого Docker-демона
 * и минуты на холодный старт. Слив их в один прогон, мы бы получили либо медленный
 * `pnpm test`, либо (что хуже) e2e, которые молча не запускаются там, где Docker недоступен.
 *
 * SWC-трансформация — та же функция, что у юнитов (jest.swc.mjs), а не копия: e2e поднимает
 * настоящий DI-контейнер Nest, и расхождение в `decoratorMetadata` сломало бы его первым.
 *
 * ВАЖНО про запуск. Скрипт test:e2e зовёт Jest через `node --experimental-vm-modules`, и это
 * не украшательство: Prisma 7 подгружает свой WASM-компилятор запросов динамическим import(),
 * а CJS-песочница Jest без этого флага отвечает «A dynamic import callback was invoked without
 * --experimental-vm-modules». Падает при этом не тест, а `app.init()` — выглядит как сломанное
 * приложение, хотя сломан только раннер. Юнитов это не касается: они не создают PrismaClient.
 *
 * @type {import('jest').Config}
 */
export default {
  rootDir: '.',
  roots: ['<rootDir>/test'],
  testEnvironment: 'node',
  testMatch: ['**/*.e2e-spec.ts'],
  moduleFileExtensions: ['ts', 'js', 'json'],

  transform: {
    '^.+\\.ts$': ['@swc/jest', loadSwcConfig()],
  },

  // Один Postgres + один Redis на весь прогон (SLT-48), а не пара контейнеров на файл: ниже
  // порога в 5 файлов такое дублирование было терпимо, но при шести спеках кратный холодный
  // старт и память перевесили. Оба хука выполняются В ОДНОМ процессе Jest (без форка между
  // ними) — на этом держится передача контейнеров из setup в teardown, см. комментарий в
  // test/helpers/container-registry.ts.
  globalSetup: '<rootDir>/test/global-setup.ts',
  globalTeardown: '<rootDir>/test/global-teardown.ts',

  testTimeout: CONTAINER_STARTUP_TIMEOUT_MS,

  // Файлы гоняются В ОДИН ПОТОК. Раньше (до общего globalSetup) причина была в том, что
  // параллельные воркеры Jest — это отдельные процессы, каждый поднял бы свою пару контейнеров.
  // Теперь контейнер один на весь прогон, и причина сменилась на противоположную: общая база
  // изолируется truncate-ом между тестами (resetDatabase), а не отдельным контейнером на файл —
  // параллельные воркеры гоняли бы truncate одного файла и запись другого одновременно, и это
  // была бы гонка, а не изоляция. maxWorkers здесь — подстраховка для прямого `jest --config
  // jest-e2e.config.mjs` без флага; штатный запуск идёт через `pnpm test:e2e`, где
  // последовательность задаёт --runInBand (см. package.json) — это единственный канал: Jest
  // принимает runInBand только аргументом CLI, статический конфиг-файл его не читает.
  maxWorkers: 1,

  // Покрытие с e2e не собираем: оно считалось бы по тому же src, что и у юнитов, и два
  // отчёта пришлось бы мержить. Цифра покрытия — забота юнит-раннера, дело e2e — контракт.
  collectCoverage: false,
};
