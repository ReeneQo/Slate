/**
 * Границы значений auth-входов. Живут в общем пакете, потому что нужны ДВУМ сторонам сразу:
 * zod-схеме, которой валидирует форму фронт, и декораторам class-validator на бэке. Копия
 * числа в любой из сторон однажды разойдётся молча — форма примет то, что сервер отвергнет
 * 400-ым (или наоборот). Одна константа на обе стороны делает расхождение невозможным.
 *
 * Рационал границ перенесён сюда из бэк-DTO (SLT-16), чтобы он жил рядом со значением, а не
 * дублировался в login/register.
 */

/**
 * MIN — нижняя планка NIST SP 800-63B. Правил сложности (заглавная/цифра/спецсимвол) НЕТ
 * намеренно: тот же стандарт от них отговаривает — они предсказуемо порождают `Password1!`
 * вместо действительно длинной парольной фразы.
 */
export const PASSWORD_MIN_LENGTH = 8;

/**
 * MAX — это НЕ про UX, а защита сервера. Без верхней границы клиент присылает пароль на
 * мегабайт, и argon2 честно жжёт на нём CPU и 19 МиБ памяти — несколько параллельных запросов
 * кладут инстанс, причём легально, ещё до всякой аутентификации. 72 — исторический предел
 * bcrypt; argon2 им не ограничен, но число достаточное и узнаваемое.
 */
export const PASSWORD_MAX_LENGTH = 72;

/** Верхняя граница имени — чтобы в БД и в чужие интерфейсы не уезжал текст произвольного размера. */
export const DISPLAY_NAME_MAX_LENGTH = 100;
