/**
 * Сверка двух множеств литералов (обычно — ключей объекта) на ТОЧНОЕ совпадение.
 *
 * Зачем это нужно рядом с `implements`. Класс, объявленный как `implements SomeInput`, компилятор
 * проверяет ровно в одну сторону: все поля контракта должны быть в классе и быть совместимы по
 * типу. Про ЛИШНИЕ поля класса `implements` молчит — они законны, ведь класс волен расширять
 * интерфейс. Для DTO это ровно та ошибка, от которой пакет и должен защищать: поле, забытое в
 * схеме, но оставшееся в DTO, означает, что фронт о нём не знает, а бэк продолжает его принимать.
 *
 * Отсюда две сущности вместо одной. `ExactKeys` возвращает `true` при совпадении и тип-маркер с
 * перечнем расхождений — иначе. Сам по себе такой тип ошибки не даёт: объявить алиас, равный
 * маркеру, компилятору не мешает. Ошибку создаёт `AssertExact`, у которого параметр ограничен
 * `true`: маркер под это ограничение не подходит, и сборка падает с сообщением, где ВИДНЫ имена
 * разошедшихся ключей.
 *
 *   export type _Keys = AssertExact<ExactKeys<keyof CreateBoardDto, keyof CreateBoardInput>>;
 *
 * Тип экспортируется намеренно: у неэкспортированного алиаса, который нигде не используется,
 * `noUnusedLocals` отобрал бы право на существование. Рантайм-следа при этом не остаётся — в
 * отличие от варианта с `const check: ... = true`, который дожил бы до бандла.
 */
export type ExactKeys<A, B> = [Exclude<A, B> | Exclude<B, A>] extends [never]
  ? true
  : { readonly keysOutOfSync: Exclude<A, B> | Exclude<B, A> };

/** Роняет компиляцию, если `ExactKeys` вернул расхождение (см. подробности выше). */
export type AssertExact<T extends true> = T;
