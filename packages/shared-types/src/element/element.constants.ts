/**
 * Границы значений элемента холста.
 *
 * Все — про защиту, а не про UX: элемент приходит из браузера, то есть от кода, который может
 * быть переписан кем угодно. Без верхних границ один запрос кладёт в jsonb мегабайты, без
 * нижних — портит отрисовку всем, кто откроет доску позже. Клиентские ограничения при этом
 * никуда не деваются: сервер их дублирует, потому что клиенту не доверяем (CLAUDE.md).
 *
 * Числа живут в общем пакете по той же причине, что и BOARD_TITLE_MAX_LENGTH: одно и то же
 * ограничение нужно zod-схемам отсюда, декораторам class-validator в apps/api и формам на
 * фронте. Вторая копия однажды разойдётся с первой, и разойдётся тихо.
 */

/** Цвет строкой (`#1e1e1e`, `rgba(...)`, имя). Формат не фиксируем — фиксируем размер. */
export const COLOR_MAX_LENGTH = 32;

/** Толщина обводки. Ноль — фигура-призрак: попадает в hit-test, но не видна. */
export const STROKE_WIDTH_MIN = 0.1;
export const STROKE_WIDTH_MAX = 100;

/** Прозрачность: 0 — невидимо, 1 — непрозрачно. */
export const OPACITY_MIN = 0;
export const OPACITY_MAX = 1;

/**
 * Габариты фигуры. Верхняя граница не про «столько не нарисуют», а про то, где начинается
 * бессмыслица: холст бесконечный, но прямоугольник шириной 1e12 ломает расчёт bounding box и
 * подгонку зума у КАЖДОГО, кто откроет доску.
 */
export const SHAPE_SIZE_MIN = 0;
export const SHAPE_SIZE_MAX = 1_000_000;

/**
 * Линия хранится плоским массивом координат `[x1, y1, x2, y2, ...]`: минимум — 4 числа (две
 * точки), длина всегда чётная.
 *
 * Максимум — предел на ОДИН элемент, а не на доску: рисование от руки добавляет точку на
 * каждое движение мыши, и без потолка одна затяжная линия превращается в жирную строку jsonb,
 * которую потом читает каждый запрос содержимого доски.
 */
export const LINE_POINTS_MIN = 4;
export const LINE_POINTS_MAX = 10_000;

/**
 * Freedraw (карандаш) хранится тем же плоским форматом, что и линия, но собирается иначе:
 * поток точек накапливается на mousemove, а не двумя концами отрезка. Минимум — 2 числа (одна
 * точка): одиночный клик без движения коммитится как точка-клякса (см. entities/canvas-element),
 * а не отбрасывается, как у остальных фигур.
 *
 * Максимум выше, чем у линии: карандашом рисуют долгими непрерывными жестами, а не двумя кликами.
 */
export const FREEDRAW_POINTS_MIN = 2;
export const FREEDRAW_POINTS_MAX = 50_000;
