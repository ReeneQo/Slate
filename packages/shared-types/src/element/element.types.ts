import { z } from 'zod';

/**
 * Типы фигур холста — СВОЙ перечень, а не реэкспорт enum'а из @slate/database.
 *
 * Соблазн взять готовое велик: enum в Prisma-схеме уже описывает ровно эти три значения. Но
 * тогда пакет контрактов начал бы зависеть от ORM, а вместе с ним — и весь фронт, который его
 * импортирует. Клиенту в браузере не нужен ни Prisma-клиент, ни его сгенерированные типы; тащить
 * их туда ради union из трёх строк значит связать форму запроса с формой таблицы. Это разные
 * вещи, которые сегодня совпадают: колонка может стать шире контракта (архивные типы фигур,
 * которые больше нельзя создавать), а контракт — уже колонки.
 *
 * Разъезд с БД при этом НЕ остаётся незамеченным: в apps/api DTO объявлены как
 * `implements`-контракты, где поле `type` типизировано enum'ом из @slate/database, а требуется
 * этот union. Стоит спискам разойтись в любую сторону — бэк не компилируется.
 *
 * Значение (`elementTypeSchema`), а не только тип: перечень нужен и в рантайме — фронту для
 * панели инструментов, схемам ниже для дискриминации.
 */
export const elementTypeSchema = z.enum(['rect', 'ellipse', 'line']);

/** Тип фигуры холста. */
export type ElementType = z.infer<typeof elementTypeSchema>;
